//! Generates bindings for every fixture IDL: the real-world IDLs of
//! `idlgen/tests/fixtures/idls` and the synthetic ones of `idls`.

use std::fmt::Write;
use std::path::Path;

use substreams_solana::Idlgen;

const FIXTURE_DIRS: &[&str] = &["../idlgen/tests/fixtures/idls", "idls"];

fn main() -> Result<(), anyhow::Error> {
    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR")?;
    let mut modules = Vec::new();

    for dir in FIXTURE_DIRS {
        println!("cargo:rerun-if-changed={dir}");
        let mut entries: Vec<_> =
            std::fs::read_dir(Path::new(&manifest_dir).join(dir))?.collect::<Result<_, _>>()?;
        entries.sort_by_key(|entry| entry.file_name());
        for entry in entries {
            let path = entry.path();
            if path.extension().is_none_or(|ext| ext != "json") {
                continue;
            }
            let name = path.file_stem().unwrap().to_string_lossy().into_owned();
            let in_path = format!("{dir}/{name}.json");
            println!("cargo:rerun-if-changed={in_path}");
            Idlgen::new(name.as_str(), in_path.as_str())?
                .generate()?
                .write_to_file(format!("src/generated/{name}.rs"))?;
            modules.push(name);
        }
    }

    let mut code = String::from(
        "// @generated\n// This file was @generated by the build script. Do not edit it by hand.\n\n",
    );
    for name in &modules {
        writeln!(code, "#[rustfmt::skip]\npub mod {name};")?;
    }
    let mod_path = Path::new(&manifest_dir).join("src/generated/mod.rs");
    if std::fs::read_to_string(&mod_path).ok().as_deref() != Some(code.as_str()) {
        std::fs::write(mod_path, code)?;
    }
    Ok(())
}
